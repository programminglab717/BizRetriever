import { fileURLToPath } from 'node:url';

import type { LoadedPack } from './loader';

export const GENERATED_FILE = fileURLToPath(new URL('./generated/packs.ts', import.meta.url));

/** Source text of `src/generated/packs.ts` for the given packs. */
export function renderGeneratedPacks(packs: LoadedPack[]): string {
  const data = Object.fromEntries(
    packs.map((p) => [
      p.manifest.id,
      {
        manifest: p.manifest,
        entities: p.entities,
        synonyms: p.synonyms,
        knownFormats: p.knownFormats,
        metrics: p.metrics,
        questions: p.questions,
        dashboard: p.dashboard,
        insights: p.insights,
        primer: p.primer,
        translations: p.translations,
      },
    ]),
  );
  return [
    '// GENERATED by `pnpm packs:build` from packages/packs/packs/*. Do not edit by hand.',
    "import type { PackData } from '../types';",
    '',
    `export const BUNDLED_PACKS: Record<string, PackData> = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');
}

export const PACK_CATALOG_FILE = fileURLToPath(
  new URL('../../i18n/src/es/packs.ts', import.meta.url),
);

/**
 * Source text of the i18n catalog `packages/i18n/src/es/packs.ts` (M20): every English text a pack
 * writes that people read as a label or note (names, descriptions, assumptions, tile titles,
 * insight names and settings), mapped to its Spanish, so screens translate it with `t.text`.
 * Insight sentences and example questions are used straight from the translation instead.
 */
export function renderPackCatalog(packs: LoadedPack[]): string {
  const map = new Map<string, string>();
  const clashes: string[] = [];
  const add = (en: string | undefined, es: string | undefined) => {
    if (!en || !es) return;
    const prev = map.get(en);
    if (prev !== undefined && prev !== es) clashes.push(`"${en}": "${prev}" or "${es}"`);
    else map.set(en, es);
  };
  for (const p of packs) {
    const tr = p.translations.es;
    if (!tr) continue;
    add(p.manifest.name, tr.manifest.name);
    add(p.manifest.description, tr.manifest.description);
    add(p.manifest.industries_label, tr.manifest.industries_label);
    p.manifest.helpful_files.forEach((h, i) => {
      add(h.what, tr.manifest.helpful_files[i]?.what);
      add(h.detail, tr.manifest.helpful_files[i]?.detail);
    });
    for (const e of p.entities) {
      const te = tr.entities[e.id];
      if (!te) continue;
      add(e.label.singular, te.singular);
      add(e.label.plural, te.plural);
      add(e.description, te.description);
      for (const f of e.fields) {
        const tf = te.fields[f.id];
        if (!tf) continue;
        add(f.label, typeof tf === 'string' ? tf : tf.label);
        if (typeof tf !== 'string') add(f.description, tf.description);
      }
    }
    for (const m of p.metrics.metrics) {
      const tm = tr.metrics[m.id];
      if (!tm) continue;
      add(m.label, tm.label);
      add(m.description, tm.description);
      add(m.unavailable_hint, tm.unavailable_hint);
      m.assumptions.forEach((a, i) => add(a, tm.assumptions[i]));
    }
    for (const d of p.metrics.dimensions) {
      const td = tr.dimensions[d.field];
      if (!td) continue;
      add(d.label, td.label);
      for (const [v, label] of Object.entries(d.value_labels)) add(label, td.value_labels[v]);
    }
    for (const x of p.dashboard.tiles) add(x.title, tr.dashboard[x.id]);
    for (const r of p.insights.rules) {
      const ti = tr.insights[r.id];
      if (!ti) continue;
      add(r.label, ti.label);
      add(r.description, ti.description);
      for (const [k, th] of Object.entries(r.thresholds)) add(th.label, ti.thresholds[k]);
      add(r.action?.label, ti.action?.label);
      if (r.action && 'ask' in r.action) add(r.action.ask, ti.action?.ask);
    }
  }
  if (clashes.length)
    throw new Error(`Packs translate the same text differently:\n${clashes.join('\n')}`);
  const entries = [...map.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return [
    '// GENERATED by `pnpm packs:build` from packages/packs/packs/*/i18n/es.yaml. Do not edit by hand.',
    '',
    '/** What the industry packs write, in Spanish (M20). */',
    `export const packs: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};`,
    '',
  ].join('\n');
}
